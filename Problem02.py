# ==========================================
# Problem 02: Variable Input and Assignment
# Description: Demonstrates capturing string input, printing it,
#              and reassigning variables.
# ==========================================

# Step 1: Prompt the user to enter their name (input() already returns a string)
name = input("Enter your name: ")

# Step 2: Display the name entered by the user
print("User name:", name)

# Step 3: Reassign the name variable with a new value
name = "Walid Rahman"

# Step 4: Display the updated name variable
print("Updated name:", name)
